// Builds the files shipped inside the plugin (plugin/onecarat-agent-office/dist):
//   dist/office.mjs                   — launcher (check/start/stop/status), one file, no dependencies
//   dist/onecarat-agent-office.exe    — the small-window app (Tauri), with the page embedded
//
//   node scripts/build-plugin.mjs            build the page, the app and the launcher
//   node scripts/build-plugin.mjs --no-app   only the launcher (keeps the exe that is already there)
//
// Windows only: the app is a Windows program.
import { build } from 'esbuild';
import { execFileSync, spawnSync } from 'node:child_process';
import crypto from 'node:crypto';
import fs from 'node:fs';
import os from 'node:os';
import path from 'node:path';

const root = path.resolve(import.meta.dirname, '..');
const dist = path.join(root, 'plugin/onecarat-agent-office/dist');
const EXE = 'onecarat-agent-office.exe';
const noApp = process.argv.includes('--no-app');
fs.mkdirSync(dist, { recursive: true });

if (!noApp) {
  if (process.platform !== 'win32') throw new Error('the app can only be built on Windows (use --no-app for the launcher alone)');
  // 1. the page, 2. the app with the page embedded ("custom-protocol" = use the embedded page, not a dev server)
  execFileSync(process.execPath, [path.join(root, 'node_modules/vite/bin/vite.js'), 'build', '--logLevel', 'warn'], { cwd: path.join(root, 'packages/office-ui'), stdio: 'inherit' });
  // The compiler writes the places of the source files into the program (for its error messages). Those are
  // folders of this PC: the user's home folder (cargo keeps the libraries there) and this repository. They are
  // replaced by plain names, so that the shipped exe names neither the Windows account nor a local path.
  const remap = [[os.homedir(), 'home'], [root, 'office']].map(([from, to]) => `--remap-path-prefix=${from}=${to}`);
  const flags = [process.env.CARGO_ENCODED_RUSTFLAGS, ...(process.env.RUSTFLAGS ?? '').split(/\s+/), ...remap].filter(Boolean).join('\x1f');
  const { RUSTFLAGS: _dropped, ...buildEnv } = process.env;
  execFileSync('cargo', ['build', '--release', '--locked', '--features', 'custom-protocol'], { cwd: path.join(root, 'src-tauri'), stdio: 'inherit', env: { ...buildEnv, CARGO_ENCODED_RUSTFLAGS: flags } });
  fs.copyFileSync(path.join(root, 'src-tauri/target/release', EXE), path.join(dist, EXE));
}

// The exe that ships (just built, or the one already there with --no-app) must not name this PC's folders or its
// Windows account. Looked for as plain text and as UTF-16, the two ways a Windows program holds text.
{
  const shipped = path.join(dist, EXE);
  if (fs.existsSync(shipped)) {
    const bytes = fs.readFileSync(shipped);
    const user = os.userInfo().username;
    const marks = [os.homedir(), os.homedir().replaceAll('\\', '/'), root, root.replaceAll('\\', '/'), ...(user.length >= 4 ? [`\\${user}\\`, `/${user}/`] : [])];
    for (const text of [bytes.toString('latin1').toLowerCase(), bytes.toString('utf16le').toLowerCase(), bytes.subarray(1).toString('utf16le').toLowerCase()]) {
      for (const m of marks) if (text.includes(m.toLowerCase())) throw new Error(`${EXE} names a folder of this PC ("${m}"): build it again with this script (without --no-app)`);
    }
  }
}

await build({
  bundle: true,
  platform: 'node',
  format: 'esm',
  target: 'node18',
  legalComments: 'eof',
  logLevel: 'warning',
  banner: { js: '// Onecarat Agent Office — generated by scripts/build-plugin.mjs from packages/launcher. Do not edit; edit the sources.' },
  entryPoints: [path.join(root, 'packages/launcher/src/cli.ts')],
  outfile: path.join(dist, 'office.mjs'),
});

// Nothing else may be in dist.
for (const f of fs.readdirSync(dist)) if (f !== 'office.mjs' && f !== EXE) throw new Error(`unexpected file in dist: ${f}`);

// Smoke test: the bundled launcher must run (catches bundling mistakes the unit tests cannot see).
// ("check" exits 1 where the app is missing or the system is not Windows; only that it ran matters here.)
const smoke = spawnSync(process.execPath, [path.join(dist, 'office.mjs'), 'check'], { encoding: 'utf8', env: { ...process.env, ONECARAT_OFFICE_RUNTIME_DIR: path.join(root, 'node_modules/.office-smoke') } });
if (!String(smoke.stdout).includes('Node.js')) throw new Error('bundled launcher did not run:\n' + smoke.stdout + smoke.stderr);

const exe = path.join(dist, EXE);
if (fs.existsSync(exe)) {
  const sha = crypto.createHash('sha256').update(fs.readFileSync(exe)).digest('hex');
  console.log(`${EXE}: ${(fs.statSync(exe).size / 1024 / 1024).toFixed(1)} MB, sha256 ${sha}`);
} else console.log(`${EXE}: not built (--no-app)`);
console.log('built', path.relative(root, dist));
