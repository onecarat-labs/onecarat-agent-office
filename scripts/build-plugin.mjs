// Builds the files shipped inside the plugin (plugin/onecarat-agent-office/dist):
//   dist/bridge.mjs  — event bridge, single file, no native modules
//   dist/office.mjs  — launcher (check/start/stop/status/open)
//   dist/ui/         — built Office UI
// CI rebuilds this and fails if the committed dist differs (so the shipped JS matches the public source).
// dist/vendor/ is NOT built here: it holds upstream node-pty files (scripts/vendor-node-pty.mjs, checked
// byte-for-byte against the npm tarball by CI) and is left untouched.
import { build } from 'esbuild';
import { execFileSync } from 'node:child_process';
import fs from 'node:fs';
import path from 'node:path';

const root = path.resolve(import.meta.dirname, '..');
const dist = path.join(root, 'plugin/onecarat-agent-office/dist');
fs.mkdirSync(dist, { recursive: true });
for (const e of fs.readdirSync(dist)) if (e !== 'vendor') fs.rmSync(path.join(dist, e), { recursive: true, force: true });

const vite = path.join(root, 'node_modules/vite/bin/vite.js');
execFileSync(process.execPath, [vite, 'build', '--outDir', path.join(dist, 'ui'), '--emptyOutDir', '--logLevel', 'warn'], {
  cwd: path.join(root, 'packages/office-ui'),
  stdio: 'inherit',
});

const common = {
  bundle: true,
  platform: 'node',
  format: 'esm',
  target: 'node18',
  legalComments: 'eof',
  logLevel: 'warning',
  banner: {
    js: [
      '// Onecarat Agent Office — generated by scripts/build-plugin.mjs from packages/*. Do not edit; edit the sources.',
      // Bundled CommonJS dependencies (ws) call require() for Node built-ins.
      "import { createRequire as __officeCreateRequire } from 'node:module'; const require = __officeCreateRequire(import.meta.url);",
    ].join('\n'),
  },
  // node-pty is loaded at run time from dist/vendor (never bundled); ws's optional native speedups are not shipped.
  external: ['node-pty', 'bufferutil', 'utf-8-validate'],
};
await build({ ...common, entryPoints: [path.join(root, 'packages/event-bridge/src/main.ts')], outfile: path.join(dist, 'bridge.mjs') });
await build({ ...common, entryPoints: [path.join(root, 'packages/launcher/src/cli.ts')], outfile: path.join(dist, 'office.mjs') });

// No native module may appear outside the verified upstream node-pty copy.
for (const f of fs.readdirSync(dist, { recursive: true })) {
  const p = String(f).split(path.sep).join('/');
  if (p.endsWith('.node') && !p.startsWith('vendor/node-pty/prebuilds/')) throw new Error(`native module in dist: ${p}`);
}
// Smoke test: the bundled bridge must actually start (catches bundling mistakes the unit tests cannot see).
{
  const { spawn } = await import('node:child_process');
  const os = await import('node:os');
  const rt = fs.mkdtempSync(path.join(os.tmpdir(), 'office-smoke-'));
  const p = spawn(process.execPath, [path.join(dist, 'bridge.mjs'), '--port', '47899', '--no-terminal'], { env: { ...process.env, ONECARAT_OFFICE_RUNTIME_DIR: rt } });
  let out = '';
  p.stdout.on('data', (d) => (out += d));
  p.stderr.on('data', (d) => (out += d));
  const ok = await new Promise((resolve) => {
    const t = setTimeout(() => resolve(false), 8000);
    p.stdout.on('data', () => out.includes('UI:') && (clearTimeout(t), resolve(true)));
    p.on('exit', () => (clearTimeout(t), resolve(false)));
  });
  p.kill();
  fs.rmSync(rt, { recursive: true, force: true });
  if (!ok) throw new Error('bundled bridge did not start:\n' + out);
}
console.log('built', path.relative(root, dist));
